"""Check that every released module is logic-identical to the original it came from.

For each released file the checker parses it and the original, removes all docstrings and the
text of argparse help arguments, and compares the two syntax trees with ast.dump. Comments never
reach the syntax tree, so they are free to differ.

The only other differences allowed are string constants that are listed in STRING_EDITS below:
file-system path defaults, and printed or raised message text. A listed string must differ in the
tree exactly where the original has a different string. Any other difference fails the file.

Usage:
  python tools/check_ast_equivalence.py --orig-root PATH_TO_ORIGINAL_PROJECT
  python tools/check_ast_equivalence.py --selftest

Prints one PASS or FAIL line per file and exits 1 if any file fails. The original project is
needed only to run this check; the released code does not depend on it.
"""
